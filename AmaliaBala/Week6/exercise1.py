numbers = [3,7,2,9,4,1,8] #list of integers
numbers.append(5) #append the num 5 to the list
numbers.remove(9) #remove the num 9 from the list
numbers.sort() #sort the list in ascending order
numbers.reverse() # reverse the sorted list
numbers.insert(2, 6) #insert the num 6 at index 2
numbers.sort(reverse=True) #sort in descending order
print(numbers.index(4)) #print the index of the num 4 in the list
print(numbers) # print the fina list after all the changes
