# =
a = 1
print(a)  # 1

# +=
a = 1
a += 1
print(a)  # 2

# -=
a = 2
a -= 1
print(a)  # 1

# *=
a = 3
a *= 2
print(a)  # 6

# /=
a = 5
a /= 2
print(a)  # 2.5

# %=
a = 5
a /= 2
print(a)  # 2.5

# //=
a = 5
a //= 2
print(a)  # 2

# **=
a = 3
a **= 2
print(a)  # 9

# &=
a = 10  # 1010
a &= 16  # 1010 & 10000
print(a)  # 00000 = 0

# |=
a = 10  # 1010
a |= 16  # 1010 | 10000
print(a)  # 11010 = 26

# ^=
a = 12  # 1100
a ^= 8  # 1100 ^ 1000
print(a)  # 0100 = 4

# >>=
a = 17  # 10001
a >>= 2  # 100 = 4
print(a)

# <<=
a = 17  # 10001
a <<= 2  # 1000100 = 68
print(a)

# :=
print(a := 17)  # 17, a = 17
