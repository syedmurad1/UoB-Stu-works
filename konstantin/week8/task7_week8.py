# &
a = 10  # 1010
b = 16  # 10000
print(a & b)  # 1010 & 10000 = 00000 = 0

# |
a = 10  # 1010
b = 16  # 10000
print(a | b)  # 1010 | 10000 = 11010 = 26

# ^
a = 12  # 1100
b = 8  # 1000
print(a ^ b)  # 1100 ^ 1000 = 0100 = 4

# ~
a = 12
print(~a)  # -12 - 1 = -13

# >>
a = 17  # 10001
b = 2
print(a >> b)  # 100 = 4

# <<
a = 17  # 10001
b = 2
print(a << b)  # 1000100 = 68
